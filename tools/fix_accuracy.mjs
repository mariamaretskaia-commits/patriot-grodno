// Правки точности: цифры со ссылкой на источник, устранение ложных
// противоречий, корректная классификация фортификаций.
// Запуск: node tools/fix_accuracy.mjs
import { readFileSync, writeFileSync } from "node:fs";

const FILE = "data/places.json";
const places = JSON.parse(readFileSync(FILE, "utf8"));

const byId = (id) => {
  const found = places.find((place) => place.id === id);
  if (!found) throw new Error("Не найдено место: " + id);
  return found;
};

const changes = [];
const touch = (id, note) => changes.push(id + " — " + note);

// 1. Белуша: 1120 относится к одной братской могиле, 8000+ — ко всему
// кладбищу. Раньше это выглядело как противоречие двух цифр.
{
  const place = byId("voinskoe-kladbische-belusha");
  const before = "Всего в братских и индивидуальных могилах захоронено свыше 8000 человек, учётный номер воинского захоронения — 2455.";
  const after =
    "Всего на кладбище, по данным izvezda.by, захоронено свыше 8000 человек. " +
    "Отдельно в государственном учёте значится братская могила учётного номера 2455, " +
    "по которой в реестре захоронений pomnim.by указано 1120 человек. " +
    "Это не две оценки одного и того же: 8000+ — всё кладбище, 1120 — только эта братская могила.";
  if (!place.full.includes(before)) throw new Error("Белуша: не найден исходный текст цифр");
  place.full = place.full.replace(before, after);
  if (!place.source.includes("pomnim.by")) {
    place.source += "; учёт братской могилы №2455 — pomnim.by (запись 71475)";
  }
  touch(place.id, "разведены 8000+ (кладбище) и 1120 (одна братская могила)");
}

// 2. Форт №2: координата подтверждена OSM, цифра «более 3000» — это надпись
// на плите, а не установленный точный итог.
{
  const place = byId("fort-2-naumovichi");
  place.coordStatus = "verified";
  const before =
    "По советским данным, за все годы оккупации нацисты расстреляли здесь более 3000 советских граждан; " +
    "это число указано на мемориальной плите у братской могилы и подтверждается актом Чрезвычайной " +
    "государственной комиссии от 4 июня 1945 года, при этом остаётся дискуссионным. " +
    "В дни оккупации казни проводились неоднократно: 20 октября 1942 года и 13 июля 1943 года.";
  const after =
    "Надпись на мемориальной плите у братской могилы сообщает, что в 1941–1943 годах на форту " +
    "расстреляно более 3000 мирных граждан и военнопленных. Число около трёх тысяч называет и " +
    "Чрезвычайная государственная комиссия по расследованию злодеяний нацистских захватчиков, " +
    "работавшая на форте весной — летом 1945 года. Точное число погибших остаётся дискуссионным: " +
    "одна и та же цифра в разных источниках относится то к общему числу жертв, то к расстрелам " +
    "в сентябре 1941 года и в феврале 1942 года, а отдельные исследователи приводят несопоставимо " +
    "более высокие оценки. Казни на форте проводились неоднократно: 20 октября 1942 года, " +
    "13 июля 1943 года и в ночь на 15 июля 1943 года.";
  if (!place.full.includes(before)) throw new Error("Форт №2: не найден исходный текст цифр");
  place.full = place.full.replace(before, after);

  const nameBefore =
    "В братской могиле на территории форта похоронена 19-летняя железнодорожная техник и активная " +
    "участница антифашистского подполья Марианна Осиповна Бирнацкая (псевдоним \"Полина\" Боброва). " +
    "Она была расстреляна 13 июля 1943 года вместе с 50 заложниками. В 1999 году за подвиг и мужество " +
    "Марианна Бирнацкая была причислена к лику святых мучениц (беатифицирована 13 июня 1999 года).";
  const nameAfter =
    "В списке на братской могиле, оформленном по материалам Чрезвычайной государственной комиссии, " +
    "значится Марьяна Бернатская (в документах — Бернатская, 1883 года рождения), 19-летняя " +
    "железнодорожная техник и участница антифашистского подполья. Она была расстреляна 13 июля 1943 года " +
    "вместе с 50 заложниками из Липска. 13 июня 1999 года Марианна Бернацкая была беатифицирована " +
    "папой римским Иоанном Павлом II, день её памяти отмечается 12 июня.";
  if (!place.full.includes(nameBefore)) throw new Error("Форт №2: не найден исходный текст о Марианне");
  place.full = place.full.replace(nameBefore, nameAfter);
  if (!place.source.includes("fortressgrodno.by")) {
    place.source += "; список братской могилы и беатификация — fortressgrodno.by";
  }
  touch(place.id, "цифра «более 3000» помечена как надпись на плите; координата подтверждена OSM");
}

// 3. Форт №1: уточнить, что это бетонный форт 1912–1915 гг., а не земляной
// форт 1887 г. в лесопарке Пышки — объекты с одинаковым номером в разных местах.
{
  const place = byId("fort-1-zagorany");
  place.short =
    "Первый большой форт Гродненской крепости на левом берегу Немана, у деревни Загораны.";
  place.full =
    "Форт №1 — первый большой форт Гродненской крепости, расположенный на левом берегу Немана " +
    "в 250 метрах от деревни Загораны. План укреплений города был утверждён 4 августа 1912 года " +
    "и предполагал 13 фортов, 23 нумерованных и 19 литерных опорных пунктов. Строительство форта " +
    "велось в 1913–1915 годах, проект составлен военным инженером капитаном Константином Никодимовичем " +
    "Добржинским в декабре 1912 года; в плане форт представлял собой пятиугольник. " +
    "К лету 1915 года головной фас бетонного бруствера был построен, но форт не был закончен даже на 50 %. " +
    "По дороге к форту, между деревнями Адамовичи и Пушкари, сохранился единственный уцелевший " +
    "крепостной бетонный мостик — остаток крепостной дороги, ведшей к группе форта. " +
    "Форт включён в промаркированный туристический маршрут «Гродненская крепость». " +
    "Внимание: не путать с земляным фортом №1 Гродненской укреплённой позиции 1887 года, " +
    "который сохранился в лесопарке Пышки, — это другой объект в другом месте.";
  place.source =
    "Форт №1, fortressgrodno.by; маршрут «Гродненская крепость» №416, grodnorik.gov.by; " +
    "Гродненская укреплённая позиция 1887 г., fortress.grodno.by; " +
    "план укреплений 1912 г. — ru.wikipedia, Гродненская крепость; координаты — OpenStreetMap";
  touch(place.id, "отделено от земляного форта №1 (1887, Пышки); уточнено состояние и маршрут");
}

// 4. ДОТ не является фортом крепости — выводим из типа «фортификация»,
// иначе значок «Хранитель фортов» считает его фортом.
{
  const place = byId("dot-sonichi");
  place.type = "дот";
  place.full =
    "ДОТ-памятник советским воинам у деревни Соничи относится к 68-му Гродненскому укрепрайону " +
    "(«Линия Молотова»), построенному в 1940–1941 годах. Это дотовое орудие, а не форт " +
    "Гродненской крепости 1912–1915 годов, поэтому в приложении оно вынесено в отдельный тип " +
    "«дот» и не учитывается в значке «Хранитель фортов».";
  place.source =
    "Паспорт объекта, mrik.gov.by; 68-й Гродненский укрепрайон, fortressgrodno.by; belarustourism.by";
  touch(place.id, "тип «фортификация» → «дот», больше не считается фортом");
}

writeFileSync(FILE, JSON.stringify(places, null, 2) + "\n", "utf8");
console.log("Изменено записей: " + changes.length);
changes.forEach((line) => console.log("  - " + line));
